"""Deterministic explanation traces built only from recorded simulation events.

Nothing here is generated by a language model. Every step cites the event IDs it is
derived from, so each explanation can be checked against ``events.csv``.

Reading a chain ``X -> Y``: X was recorded as blocking Y. For a cash shortfall, the
link points to the payer's *overdue incoming payments* at the hour the payment was
cash-blocked (the largest one is followed; all are listed). This is a recorded
dependency, not a counterfactual proof that this delay alone caused the shortfall.
"""

from __future__ import annotations

from bisect import bisect_right
from collections import defaultdict
from dataclasses import dataclass
from typing import Any

from .engine import BlockRecord, SimulationResult, Status
from .models import Scenario

CAVEAT = (
    "Arrows show recorded blocking relationships: an operational block points to the unavailable "
    "service and its failed dependencies; a cash block points to the payer's overdue incoming payments "
    "at that hour (largest first). They are not a proof that the linked delay alone caused the shortfall; "
    "compare with the baseline run for that."
)


@dataclass(frozen=True)
class TraceStep:
    kind: str  # disruption | service | payment_blocked | cash_shortfall | payment_outcome
    short: str  # compact label for the one-line chain
    text: str  # full sentence
    hour: int | None
    event_ids: tuple[int, ...]
    ref: str | None


@dataclass(frozen=True)
class Explanation:
    obligation_id: str
    headline: str
    chain: tuple[TraceStep, ...]  # root cause first, explained obligation last
    segments: tuple[dict[str, Any], ...]  # blocked hours grouped by identical reasons
    linked_inflows: tuple[dict[str, Any], ...]  # overdue inflows at the first cash block
    caveat: str = CAVEAT

    def chain_text(self) -> str:
        return " → ".join(step.short for step in self.chain)


class Explainer:
    """Builds explanations for one simulation result (indexes are built once)."""

    def __init__(self, result: SimulationResult):
        self.r = result
        self.s: Scenario = result.scenario
        self.names = result.scenario.names()
        self.obligations = result.scenario.obligations_by_id()
        self.blocks = result.blocks_by_obligation()
        self.currency = result.scenario.currency
        self._state_events: dict[str, list[tuple[int, int]]] = defaultdict(list)
        for e in result.events:
            if e.type == "SERVICE_STATE" and e.service_id:
                self._state_events[e.service_id].append((e.hour, e.event_id))
        self._disruptions = {d.id: d for d in result.effective_disruptions}

    # ------------------------------------------------------------- helpers

    def money(self, minor: int) -> str:
        return self.currency.format(minor)

    def name(self, ident: str) -> str:
        return self.names.get(ident, ident)

    def label(self, oid: str) -> str:
        ob = self.obligations[oid]
        purpose = f" {ob.purpose}" if ob.purpose else ""
        return f"{oid}{purpose} ({self.name(ob.payer)} → {self.name(ob.recipient)}, {self.money(ob.amount)})"

    def _state_event(self, service_id: str, hour: int) -> int | None:
        events = self._state_events.get(service_id, [])
        index = bisect_right([h for h, _ in events], hour) - 1
        return events[index][1] if index >= 0 else None

    def _outcome_step(self, oid: str) -> TraceStep:
        o = self.r.outcomes[oid]
        ob = self.obligations[oid]
        short_name = f"{oid} {ob.purpose}".strip()
        if o.status is Status.SETTLED_ON_TIME:
            return TraceStep("payment_outcome", f"{short_name} on time",
                             f"{self.label(oid)} settled on time in hour {o.settled_hour} via {o.route_used}.",
                             o.settled_hour, (o.settlement_event_id,), oid)
        if o.status is Status.SETTLED_LATE:
            via = " (backup route)" if o.via_backup else ""
            return TraceStep("payment_outcome", f"{short_name} delayed {o.delay_hours} h",
                             f"{self.label(oid)} was due in hour {o.due_hour} and settled in hour {o.settled_hour} "
                             f"via {o.route_used}{via}: {o.delay_hours} h late.",
                             o.settled_hour, (o.settlement_event_id,), oid)
        last = self.blocks[oid][-1]
        return TraceStep("payment_outcome", f"{short_name} unsettled at horizon",
                         f"{self.label(oid)} was due in hour {o.due_hour} and was still unsettled at the horizon "
                         f"(last reasons: {', '.join(last.reasons)}).",
                         self.s.horizon_hours - 1, (last.event_id,), oid)

    def service_chain(self, service_id: str, hour: int) -> list[TraceStep]:
        """Root disruption first, then each failed service up to ``service_id``."""
        status = self.r.service_status[hour]
        walk: list[TraceStep] = []
        root: TraceStep | None = None
        current: str | None = service_id
        seen: set[str] = set()
        while current is not None and current not in seen:
            seen.add(current)
            st = status[current]
            event_id = self._state_event(current, hour)
            refs = (event_id,) if event_id else ()
            disruptions = [c for c in st.causes if c["type"] == "disruption"]
            dependencies = [c for c in st.causes if c["type"] == "dependency"]
            state = st.state.value
            if disruptions:
                d = self._disruptions.get(disruptions[0]["disruption"])
                walk.append(TraceStep("service", f"{self.name(current)} {state}",
                                      f"{self.name(current)} was {state} in hour {hour} (capacity {st.pct}%) "
                                      f"because of disruption {disruptions[0]['disruption']} ({disruptions[0]['phase']}).",
                                      hour, refs, current))
                if d is not None:
                    root = TraceStep("disruption", f"Disruption {d.id}",
                                     f"Disruption {d.id}: {self.name(d.service)} at {100 - d.severity_pct}% capacity "
                                     f"from hour {d.start_hour} for {d.duration_hours} h"
                                     + (f", then {d.recovery_hours} h at {d.recovery_capacity_pct}%" if d.recovery_hours else "")
                                     + ".", d.start_hour, refs, d.id)
                break
            if not dependencies:
                walk.append(TraceStep("service", f"{self.name(current)} {state}",
                                      f"{self.name(current)} was {state} in hour {hour}.", hour, refs, current))
                break
            cause = dependencies[0]
            members = ", ".join(self.name(m) for m in cause["services"])
            relation = "requires" if cause["mode"] == "required" else "can use any of"
            walk.append(TraceStep("service", f"{self.name(current)} {state}",
                                  f"{self.name(current)} was {state} in hour {hour}: it {relation} {members}, "
                                  f"which {'was' if cause['mode'] == 'required' else 'were all'} at {cause['pct']}% capacity.",
                                  hour, refs, current))
            current = next(m for m in sorted(cause["services"]) if status[m].pct == cause["pct"])
        steps = list(reversed(walk))
        return ([root] if root else []) + steps

    def _first_block_step(self, oid: str, block: BlockRecord) -> tuple[list[TraceStep], TraceStep]:
        """(upstream operational steps, the blocked-payment step) for an operational block."""
        ob = self.obligations[oid]
        unavailable = [c for c in block.route_checks if c["status"] == "SERVICE_UNAVAILABLE"]
        exhausted = [c for c in block.route_checks if c["status"] == "CAPACITY_EXHAUSTED"]
        not_active = [c for c in block.route_checks if c["status"] == "ROUTE_NOT_YET_ACTIVE"]
        upstream: list[TraceStep] = []
        parts = []
        if unavailable:
            check = unavailable[0]
            upstream = self.service_chain(check["services"][0], block.hour)
            parts.append(f"route {check['route']} unavailable ({', '.join(self.name(s) for s in check['services'])})")
        if exhausted:
            check = exhausted[0]
            svc = check["services"][0]
            st = self.r.service_status[block.hour][svc]
            used = self.r.hours[block.hour].service_used.get(svc, 0)
            if not upstream:
                upstream = [TraceStep("service", f"{self.name(svc)} at capacity",
                                      f"{self.name(svc)} processed {used} of {st.capacity} possible payments in hour "
                                      f"{block.hour} (capacity {st.pct}% of nominal); the queue exceeded shared capacity.",
                                      block.hour, (), svc)]
            parts.append(f"route {check['route']} at capacity ({self.name(svc)})")
        if not_active:
            parts.append(f"backup route {not_active[0]['route']} not active until hour {not_active[0]['active_from_hour']}")
        if block.cash:
            parts.append(f"and {self.name(ob.payer)} also lacked cash")
        short = f"{oid} {ob.purpose}".strip() + " blocked"
        step = TraceStep("payment_blocked", short,
                         f"{self.label(oid)} could not settle in hour {block.hour}: " + "; ".join(parts) + ".",
                         block.hour, (block.event_id,), oid)
        return upstream, step

    # --------------------------------------------------------------- main

    def _chain(self, oid: str, depth: int, max_depth: int, visited: set[str]) -> list[TraceStep]:
        visited.add(oid)
        outcome_step = self._outcome_step(oid)
        blocks = self.blocks.get(oid, [])
        if not blocks:
            return [outcome_step]
        first = blocks[0]
        ob = self.obligations[oid]
        if first.operational:
            upstream, blocked = self._first_block_step(oid, first)
            return upstream + [blocked, outcome_step]
        # Cash-only block: the payer's account could not fund the payment although a route was usable.
        if first.held_by_reserve:
            text = (f"In hour {first.hour} {self.name(ob.payer)} could have paid {self.money(ob.amount)} for {oid} "
                    f"(a route was usable) but held it back: its reserve rule kept {self.money(first.reserved or 0)} "
                    f"for its own priority payments due soon, out of {self.money(first.available_cash or 0)} available.")
            short = f"{self.name(ob.payer)} held it back (reserve)"
        else:
            kept = (f", of which {self.money(first.reserved)} was kept back for its own priority payments"
                    if first.reserved else "")
            text = (f"In hour {first.hour} {self.name(ob.payer)} had {self.money(first.available_cash or 0)} available"
                    f"{kept} but needed {self.money(ob.amount)} for {oid} (a route was usable).")
            short = f"{self.name(ob.payer)} cash insufficient"
        text += (f" It was owed {self.money(first.overdue_inflow_value)} in {len(first.overdue_inflows)} overdue incoming "
                 "payment(s).")
        cash_step = TraceStep("cash_shortfall", short, text, first.hour, (first.event_id,), ob.payer)
        upstream: list[TraceStep] = []
        if depth < max_depth:
            for inflow_id, _amount in first.overdue_inflows:
                if inflow_id not in visited:
                    upstream = self._chain(inflow_id, depth + 1, max_depth, visited)
                    break
        return upstream + [cash_step, outcome_step]

    def explain(self, oid: str, max_depth: int = 8) -> Explanation:
        if oid not in self.r.outcomes:
            raise KeyError(oid)
        chain = self._chain(oid, 0, max_depth, set())
        blocks = self.blocks.get(oid, [])
        segments: list[dict[str, Any]] = []
        for b in blocks:
            if segments and segments[-1]["reasons"] == list(b.reasons) and segments[-1]["to_hour"] == b.hour - 1:
                segments[-1]["to_hour"] = b.hour
                segments[-1]["event_ids"].append(b.event_id)
            else:
                segments.append({
                    "from_hour": b.hour,
                    "to_hour": b.hour,
                    "reasons": list(b.reasons),
                    "route_checks": [dict(c) for c in b.route_checks],
                    "available_cash": b.available_cash,
                    "shortfall": b.shortfall,
                    "overdue_inflow_value": b.overdue_inflow_value if b.cash else None,
                    "event_ids": [b.event_id],
                })
        first_cash = next((b for b in blocks if b.cash), None)
        inflows = []
        if first_cash is not None:
            for inflow_id, amount in first_cash.overdue_inflows:
                o = self.r.outcomes[inflow_id]
                inflows.append({
                    "obligation_id": inflow_id,
                    "payer": o.payer,
                    "amount": amount,
                    "status": o.status.value,
                    "settled_hour": o.settled_hour,
                    "mechanism": o.mechanism.value,
                })
        outcome = self.r.outcomes[oid]
        if outcome.status is Status.SETTLED_ON_TIME:
            headline = f"{oid} settled on time."
        elif outcome.status is Status.SETTLED_LATE:
            headline = f"{oid} settled {outcome.delay_hours} h late ({outcome.mechanism.value.replace('_', ' ')})."
        else:
            headline = f"{oid} was still unsettled at the horizon ({outcome.mechanism.value.replace('_', ' ')})."
        return Explanation(oid, headline, tuple(chain), tuple(segments), tuple(inflows))


def explain(result: SimulationResult, obligation_id: str, max_depth: int = 8) -> Explanation:
    return Explainer(result).explain(obligation_id, max_depth=max_depth)
